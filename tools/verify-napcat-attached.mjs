import assert from 'node:assert/strict';
import fs from 'node:fs';

const unit = fs.readFileSync(new URL('./wsl-napcat-attached.service', import.meta.url), 'utf8');
assert.ok(unit.includes('docker run --rm --network host --name napcat-runtime --volumes-from napcat'));
assert.ok(unit.includes('napcat-nogpu-entrypoint.sh'));
assert.ok(!unit.includes('-p 127.0.0.1:3003:3001'));
assert.ok(unit.includes('--env-file /opt/habitat/state/napcat-runtime.env'));
assert.ok(!unit.includes('ACCOUNT='));
assert.ok(unit.includes('Restart=no'));
assert.ok(!unit.includes('Restart=on-failure'));
assert.ok(!unit.includes('ExecStartPre'));
assert.ok(unit.includes('ExecStop=-/usr/bin/docker stop --timeout 15 napcat-runtime'));
assert.ok(unit.includes('TimeoutStopSec=45'));
const start = fs.readFileSync(new URL('./wsl-start-adapters.sh', import.meta.url), 'utf8');
const stop = fs.readFileSync(new URL('./wsl-stop.sh', import.meta.url), 'utf8');
assert.ok(start.includes('systemctl start napcat-attached.service'));
assert.ok(start.includes('napcat-runtime.env'));
assert.ok(stop.includes('systemctl stop napcat-attached.service'));
assert.ok(stop.includes('for container in napcat-runtime napcat'));
const install = fs.readFileSync(new URL('./wsl-install.sh', import.meta.url), 'utf8');
assert.ok(install.includes('fishbowl-world napcat-attached'));
assert.ok(install.includes('onebot-host-network.conf'));
const onebotHost = fs.readFileSync(new URL('./onebot-host-network.conf', import.meta.url), 'utf8');
assert.ok(onebotHost.includes('HABITAT_ONEBOT_HTTP_URL=http://127.0.0.1:3001'));
const noGpu = fs.readFileSync(new URL('./napcat-nogpu-entrypoint.sh', import.meta.url), 'utf8');
assert.ok(noGpu.includes('--disable-gpu'));
assert.ok(noGpu.includes('/tmp/habitat-nogpu-entrypoint.sh'));
assert.ok(!noGpu.includes('entrypoint.sh > /app/entrypoint.sh'));
console.log('ok: NapCat 附着运行容器、持久化卷与受保护配置、明确失败状态和启停接入');
