// Agent 可见的推流调度投影：不包含 RTMP 地址、推流码、凭证或 Owner 的 intentId。
export function agentStreamStatus(status, policy) {
  const ownPending = status.pending?.actor === 'agent' ? status.pending : null;
  const ownSession = status.lastActor === 'agent';
  return {
    available: true,
    state: status.state,
    started: status.started,
    live: status.live,
    sessionActor: status.lastActor || null,
    lastIntentId: ownSession ? status.lastIntentId : null,
    canStop: policy.autonomous !== 'off' && Boolean(ownPending?.intentId || (ownSession && status.lastIntentId)),
    pending: ownPending ? {
      action: ownPending.action,
      room: ownPending.room,
      scene: ownPending.scene,
      maxDurationMs: ownPending.maxDurationMs,
      intentId: ownPending.intentId,
      nextAllowedAt: ownPending.nextAllowedAt,
      reason: ownPending.reason,
    } : null,
    startedAt: status.startedAt,
    lastStoppedAt: status.lastStoppedAt,
    cooldownUntil: status.cooldownUntil,
    stopReason: status.stopReason,
    lastError: status.lastError,
    dailyMs: status.dailyMs,
    dailyDate: status.dailyDate,
    maxDurationMs: status.maxDurationMs,
    maxDailyMs: status.maxDailyMs,
    room: status.room,
    scene: status.scene,
    canStart: status.canStart,
    requiresRefresh: status.requiresRefresh,
    output: {
      state: status.output?.state || 'stopped',
      frames: status.output?.frames || 0,
      lastError: status.output?.lastError || null,
    },
    verification: {
      state: status.verification?.state || 'stopped',
      verified: status.verification?.verified === true,
      lastCheckedAt: status.verification?.lastCheckedAt || null,
      lastVerifiedAt: status.verification?.lastVerifiedAt || null,
      liveStatus: status.verification?.liveStatus ?? null,
      playbackDecoded: status.verification?.playbackDecoded === true,
      lastError: status.verification?.lastError || null,
    },
    network: {
      mode: status.network?.mode || 'direct',
      supported: status.network?.supported !== false,
      lastResult: status.network?.lastResult || 'unknown',
      lastError: status.network?.lastError || null,
    },
    policy: {
      autonomous: policy.autonomous,
      allowedOutputs: [...policy.allowedOutputs],
      rooms: [...policy.rooms],
      scenes: [...policy.scenes],
      maxDurationMs: policy.maxDurationMs,
      maxDailyMs: policy.maxDailyMs,
      cooldownMs: policy.cooldownMs,
      stopOnEvidenceFailure: policy.stopOnEvidenceFailure,
      requireVerified: policy.requireVerified,
      verificationTimeoutMs: policy.verificationTimeoutMs,
      timeZone: policy.timeZone,
      windows: policy.windows.map((window) => ({ ...window, days: [...window.days] })),
    },
  };
}
